      localStorage.removeItem('heroesSelections');
      localStorage.removeItem('currentPlayerSelecting');
      localStorage.removeItem('finalHeroesSelection');
      
      // Зберігаємо список активних гравців
      localStorage.setItem('activePlayers', JSON.stringify(activePlayers));
      localStorage.setItem('currentPlayerSelecting', activePlayers[0].toString());
      
